#!/usr/bin/env python3
"""Regenerate log.txt with last-update times for the 2 tracked deliverables.

Called by .github/workflows/update-sitemap-llms.yml as part of the commit step. For files changed in this run (passed via the
CHANGED env var — a space-separated list from `git diff --cached --name-only`),
the current GMT+3 time is used. For other tracked files, `git log -1 --format=%cI`
returns the most recent commit timestamp touching them.

weglot.csv and its "Upload to Weglot" signal are gone (monorepo CEL-104): the file
was retired with the old Weglot exclusion tools and no longer exists.

No side effects at import time. Run locally with CHANGED="" to seed log.txt
from pure git history.
"""
from __future__ import annotations

import os
import pathlib
import subprocess
import sys
from datetime import datetime, timedelta, timezone

TRACKED = ("sitemap.xml", "llms.txt")
SITEMAP_URL = "https://cel.englishcollege.com/sitemap.xml"
LLMS_URL = "https://cel.englishcollege.com/llms.txt"

# Display timezone. Turkey is fixed GMT+3 year-round (no DST since 2016),
# so a plain fixed offset is correct and avoids the tzdata dependency.
TZ_DISPLAY = timezone(timedelta(hours=3))

URLS = {
    "sitemap.xml": SITEMAP_URL,
    "llms.txt": LLMS_URL,
}


def git_last_touched(path: str) -> str:
    """Return 'YYYY-MM-DD HH:MM GMT+3' of last commit touching path, or 'never'."""
    try:
        r = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--", path],
            capture_output=True,
            text=True,
            check=True,
        )
    except (FileNotFoundError, subprocess.CalledProcessError):
        return "never"
    raw = r.stdout.strip()
    if not raw:
        return "never"
    try:
        dt = datetime.fromisoformat(raw)
    except ValueError:
        return "never"
    return dt.astimezone(TZ_DISPLAY).strftime("%Y-%m-%d %H:%M GMT+3")


def build_entries(now: str, changed: set[str]) -> dict[str, str]:
    """Build {filename: timestamp} for every TRACKED file.

    After the docs/ restructure, sitemap.xml + llms.txt live at docs/<name>.
    CHANGED env var reflects actual paths from `git diff --cached --name-only`.
    """
    out: dict[str, str] = {}
    for name in TRACKED:
        docs_path = f"docs/{name}"
        is_changing = name in changed or docs_path in changed
        out[name] = now if is_changing else git_last_touched(docs_path)
    return out


def render(entries: dict[str, str]) -> str:
    lines = ["Last updated (GMT+3 — auto-generated by GitHub Actions):", ""]
    for name in TRACKED:
        lines.append(f"  {name:<12}  {entries[name]}")
        lines.append(f"    URL: {URLS[name]}")
    return "\n".join(lines) + "\n"


def main() -> int:
    changed = set(os.environ.get("CHANGED", "").split())
    now = datetime.now(TZ_DISPLAY).strftime("%Y-%m-%d %H:%M GMT+3")
    entries = build_entries(now, changed)
    pathlib.Path("docs/log.txt").parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path("docs/log.txt").write_text(render(entries), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
